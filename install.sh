#!/usr/bin/env sh
# Photo-Mem installer for macOS and Linux.
#
#   curl -fsSL https://raw.githubusercontent.com/Bloxx-I/Photo-Mem/HEAD/install.sh | sh
#
# Installs the app to ~/.local/share/photo-mem and adds the command `photo-mem`
# (start the app), `photo-mem update` and `photo-mem uninstall`.
#
# On your AI server, run it there and then `photo-mem lan`: LLM and Whisper on
# the same machine are found automatically and the network address is printed.
set -eu

REPO="Bloxx-I/Photo-Mem"
REF="${PHOTO_MEM_REF:-HEAD}"
PREFIX="${PHOTO_MEM_HOME:-$HOME/.local/share/photo-mem}"
BIN_DIR="${PHOTO_MEM_BIN:-$HOME/.local/bin}"
PORT="${PHOTO_MEM_PORT:-8765}"

say() { printf '\033[1;33m▸\033[0m %s\n' "$*"; }
die() { printf '\033[1;31m✗ %s\033[0m\n' "$*" >&2; exit 1; }

command -v python3 >/dev/null 2>&1 || die "python3 wird benötigt (macOS: 'xcode-select --install', Linux: Paketmanager)."

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

if [ -n "${PHOTO_MEM_SOURCE:-}" ]; then
  say "Kopiere App aus $PHOTO_MEM_SOURCE"
  mkdir -p "$TMP/src"
  cp -R "$PHOTO_MEM_SOURCE"/. "$TMP/src/"
else
  command -v curl >/dev/null 2>&1 || die "curl wird benötigt."
  say "Lade Photo-Mem von GitHub ($REPO@$REF)"
  curl -fsSL "https://github.com/$REPO/archive/$REF.tar.gz" -o "$TMP/app.tar.gz" || die "Download fehlgeschlagen."
  mkdir -p "$TMP/src"
  tar -xzf "$TMP/app.tar.gz" -C "$TMP/src" --strip-components=1
fi

[ -f "$TMP/src/index.html" ] || die "Download unvollständig – index.html fehlt."

say "Installiere nach $PREFIX"
mkdir -p "$PREFIX" "$BIN_DIR"
rm -rf "$PREFIX/app"
mkdir -p "$PREFIX/app"
for f in index.html styles.css app.js content.js recall.js ai.js serve.py sw.js manifest.webmanifest; do
  cp "$TMP/src/$f" "$PREFIX/app/"
done
cp -R "$TMP/src/icons" "$PREFIX/app/"
cp "$TMP/src/uninstall.sh" "$PREFIX/uninstall.sh"
chmod +x "$PREFIX/uninstall.sh"

# Settings survive updates; values passed via environment win.
CONFIG="$PREFIX/config"
if [ ! -f "$CONFIG" ] || [ -n "${PHOTO_MEM_LLM_URL:-}${PHOTO_MEM_WHISPER_URL:-}${PHOTO_MEM_BIND:-}" ]; then
  # Keep existing settings, but let values passed now take precedence.
  _bind="${PHOTO_MEM_BIND:-}"; _llm="${PHOTO_MEM_LLM_URL:-}"; _whisper="${PHOTO_MEM_WHISPER_URL:-}"
  _cert="${PHOTO_MEM_TLS_CERT:-}"; _key="${PHOTO_MEM_TLS_KEY:-}"
  [ -f "$CONFIG" ] && . "$CONFIG"
  PHOTO_MEM_BIND="${_bind:-${PHOTO_MEM_BIND:-}}"; PHOTO_MEM_LLM_URL="${_llm:-${PHOTO_MEM_LLM_URL:-}}"
  PHOTO_MEM_WHISPER_URL="${_whisper:-${PHOTO_MEM_WHISPER_URL:-}}"
  PHOTO_MEM_TLS_CERT="${_cert:-${PHOTO_MEM_TLS_CERT:-}}"; PHOTO_MEM_TLS_KEY="${_key:-${PHOTO_MEM_TLS_KEY:-}}"
  cat > "$CONFIG" <<CONF
# Photo-Mem settings – edit and run: photo-mem stop && photo-mem
PHOTO_MEM_PORT="${PHOTO_MEM_PORT:-$PORT}"
PHOTO_MEM_BIND="${PHOTO_MEM_BIND:-127.0.0.1}"      # 0.0.0.0 = reachable from phone/LAN
PHOTO_MEM_LLM_URL="${PHOTO_MEM_LLM_URL:-}"         # empty = find automatically, or e.g. http://localhost:11434, or off
PHOTO_MEM_WHISPER_URL="${PHOTO_MEM_WHISPER_URL:-}" # empty = find automatically, or e.g. http://localhost:8000, or off
PHOTO_MEM_TLS_CERT="${PHOTO_MEM_TLS_CERT:-}"       # optional HTTPS (needed for the mic on phones)
PHOTO_MEM_TLS_KEY="${PHOTO_MEM_TLS_KEY:-}"
CONF
fi

cat > "$BIN_DIR/photo-mem" <<LAUNCHER
#!/usr/bin/env sh
# Photo-Mem launcher (generated by install.sh)
PREFIX="$PREFIX"
[ -f "\$PREFIX/config" ] && . "\$PREFIX/config"
export PHOTO_MEM_PORT PHOTO_MEM_BIND PHOTO_MEM_LLM_URL PHOTO_MEM_WHISPER_URL PHOTO_MEM_TLS_CERT PHOTO_MEM_TLS_KEY
PORT="\${PHOTO_MEM_PORT:-$PORT}"
SCHEME=http; [ -n "\${PHOTO_MEM_TLS_CERT:-}" ] && SCHEME=https
URL="\$SCHEME://localhost:\$PORT/"

case "\${1:-start}" in
  uninstall) exec sh "\$PREFIX/uninstall.sh" ;;
  update) curl -fsSL "https://raw.githubusercontent.com/$REPO/HEAD/install.sh" | sh; exit \$? ;;
  stop)
    [ -f "\$PREFIX/server.pid" ] && kill "\$(cat "\$PREFIX/server.pid")" 2>/dev/null
    rm -f "\$PREFIX/server.pid"; echo "Photo-Mem gestoppt."; exit 0 ;;
  config) echo "Einstellungen: \$PREFIX/config"; cat "\$PREFIX/config"; exit 0 ;;
  lan)
    # Make the app reachable from phone/PC in the same network.
    sed -i.bak 's/^PHOTO_MEM_BIND=.*/PHOTO_MEM_BIND="0.0.0.0"      # 0.0.0.0 = reachable from phone\/LAN/' "\$PREFIX/config" && rm -f "\$PREFIX/config.bak"
    "\$0" stop >/dev/null; exec "\$0" ;;
  local)
    sed -i.bak 's/^PHOTO_MEM_BIND=.*/PHOTO_MEM_BIND="127.0.0.1"    # 0.0.0.0 = reachable from phone\/LAN/' "\$PREFIX/config" && rm -f "\$PREFIX/config.bak"
    "\$0" stop >/dev/null; exec "\$0" ;;
  info) cat "\$PREFIX/server.log" 2>/dev/null || echo "Läuft nicht."; exit 0 ;;
  start) ;;
  *) echo "Verwendung: photo-mem [start|stop|lan|local|info|config|update|uninstall]"; exit 1 ;;
esac

if ! { [ -f "\$PREFIX/server.pid" ] && kill -0 "\$(cat "\$PREFIX/server.pid")" 2>/dev/null; }; then
  nohup python3 "\$PREFIX/app/serve.py" --port "\$PORT" >"\$PREFIX/server.log" 2>&1 &
  echo \$! >"\$PREFIX/server.pid"
  # Wait until the server has searched for LLM/Whisper and printed its addresses.
  i=0; while [ \$i -lt 40 ] && ! grep -q "^Whisper:" "\$PREFIX/server.log" 2>/dev/null; do sleep 0.5; i=\$((i+1)); done
fi

cat "\$PREFIX/server.log"
echo "(beenden: photo-mem stop · fürs Handy: photo-mem lan)"
if command -v open >/dev/null 2>&1; then open "\$URL"
elif command -v xdg-open >/dev/null 2>&1; then xdg-open "\$URL" >/dev/null 2>&1
fi
LAUNCHER
chmod +x "$BIN_DIR/photo-mem"

# Linux app-menu entry
if [ "$(uname -s)" = "Linux" ]; then
  APPS="${XDG_DATA_HOME:-$HOME/.local/share}/applications"
  mkdir -p "$APPS"
  cat > "$APPS/photo-mem.desktop" <<DESKTOP
[Desktop Entry]
Type=Application
Name=Photo-Mem
Comment=Gedächtnistraining
Exec=$BIN_DIR/photo-mem
Icon=$PREFIX/app/icons/icon.svg
Terminal=false
Categories=Education;
DESKTOP
fi

say "Fertig! Starte die App mit:  photo-mem"
case ":$PATH:" in
  *":$BIN_DIR:"*) ;;
  *) say "Hinweis: $BIN_DIR ist nicht im PATH. Füge zu ~/.zshrc bzw. ~/.bashrc hinzu:  export PATH=\"$BIN_DIR:\$PATH\"" ;;
esac
say "Auf dem KI-Server fürs Handy freigeben: photo-mem lan"
say "Einstellungen (KI-Server, Port, HTTPS): photo-mem config"
say "Deinstallieren: photo-mem uninstall"
