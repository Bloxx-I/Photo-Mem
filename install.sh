#!/usr/bin/env sh
# Photo-Mem installer for macOS and Linux.
#
#   curl -fsSL https://raw.githubusercontent.com/Bloxx-I/Photo-Mem/HEAD/install.sh | sh
#
# Installs the app to ~/.local/share/photo-mem and adds the command `photo-mem`
# (start the app), `photo-mem update` and `photo-mem uninstall`.
set -eu

REPO="Bloxx-I/Photo-Mem"
REF="${PHOTO_MEM_REF:-HEAD}"
PREFIX="${PHOTO_MEM_HOME:-$HOME/.local/share/photo-mem}"
BIN_DIR="${PHOTO_MEM_BIN:-$HOME/.local/bin}"
PORT="${PHOTO_MEM_PORT:-8765}"

say() { printf '\033[1;33m▸\033[0m %s\n' "$*"; }
die() { printf '\033[1;31m✗ %s\033[0m\n' "$*" >&2; exit 1; }

command -v python3 >/dev/null 2>&1 || die "python3 wird benötigt (macOS: 'xcode-select --install', Linux: Paketmanager)."

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

if [ -n "${PHOTO_MEM_SOURCE:-}" ]; then
  say "Kopiere App aus $PHOTO_MEM_SOURCE"
  mkdir -p "$TMP/src"
  cp -R "$PHOTO_MEM_SOURCE"/. "$TMP/src/"
else
  command -v curl >/dev/null 2>&1 || die "curl wird benötigt."
  say "Lade Photo-Mem von GitHub ($REPO@$REF)"
  curl -fsSL "https://github.com/$REPO/archive/$REF.tar.gz" -o "$TMP/app.tar.gz" || die "Download fehlgeschlagen."
  mkdir -p "$TMP/src"
  tar -xzf "$TMP/app.tar.gz" -C "$TMP/src" --strip-components=1
fi

[ -f "$TMP/src/index.html" ] || die "Download unvollständig – index.html fehlt."

say "Installiere nach $PREFIX"
mkdir -p "$PREFIX" "$BIN_DIR"
rm -rf "$PREFIX/app"
mkdir -p "$PREFIX/app"
for f in index.html styles.css app.js content.js recall.js sw.js manifest.webmanifest; do
  cp "$TMP/src/$f" "$PREFIX/app/"
done
cp -R "$TMP/src/icons" "$PREFIX/app/"
cp "$TMP/src/uninstall.sh" "$PREFIX/uninstall.sh"
chmod +x "$PREFIX/uninstall.sh"

cat > "$BIN_DIR/photo-mem" <<LAUNCHER
#!/usr/bin/env sh
# Photo-Mem launcher (generated by install.sh)
PREFIX="$PREFIX"
PORT="\${PHOTO_MEM_PORT:-$PORT}"
URL="http://localhost:\$PORT/"

case "\${1:-start}" in
  uninstall) exec sh "\$PREFIX/uninstall.sh" ;;
  update) curl -fsSL "https://raw.githubusercontent.com/$REPO/HEAD/install.sh" | sh; exit \$? ;;
  stop)
    [ -f "\$PREFIX/server.pid" ] && kill "\$(cat "\$PREFIX/server.pid")" 2>/dev/null
    rm -f "\$PREFIX/server.pid"; echo "Photo-Mem gestoppt."; exit 0 ;;
  start) ;;
  *) echo "Verwendung: photo-mem [start|stop|update|uninstall]"; exit 1 ;;
esac

if ! { [ -f "\$PREFIX/server.pid" ] && kill -0 "\$(cat "\$PREFIX/server.pid")" 2>/dev/null; }; then
  nohup python3 -m http.server "\$PORT" --bind 127.0.0.1 --directory "\$PREFIX/app" >"\$PREFIX/server.log" 2>&1 &
  echo \$! >"\$PREFIX/server.pid"
  sleep 1
fi

echo "Photo-Mem läuft auf \$URL  (beenden: photo-mem stop)"
if command -v open >/dev/null 2>&1; then open "\$URL"
elif command -v xdg-open >/dev/null 2>&1; then xdg-open "\$URL" >/dev/null 2>&1
fi
LAUNCHER
chmod +x "$BIN_DIR/photo-mem"

# Linux app-menu entry
if [ "$(uname -s)" = "Linux" ]; then
  APPS="${XDG_DATA_HOME:-$HOME/.local/share}/applications"
  mkdir -p "$APPS"
  cat > "$APPS/photo-mem.desktop" <<DESKTOP
[Desktop Entry]
Type=Application
Name=Photo-Mem
Comment=Gedächtnistraining
Exec=$BIN_DIR/photo-mem
Icon=$PREFIX/app/icons/icon.svg
Terminal=false
Categories=Education;
DESKTOP
fi

say "Fertig! Starte die App mit:  photo-mem"
case ":$PATH:" in
  *":$BIN_DIR:"*) ;;
  *) say "Hinweis: $BIN_DIR ist nicht im PATH. Füge zu ~/.zshrc bzw. ~/.bashrc hinzu:  export PATH=\"$BIN_DIR:\$PATH\"" ;;
esac
say "Deinstallieren: photo-mem uninstall"
